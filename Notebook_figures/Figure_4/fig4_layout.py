def annotation_xy(parent_rect, pos_mm):
    """(x, y) in FIGURE fractions for an annotation hung off `parent_rect`.

    `pos_mm` is millimetres from the parent panel's bottom-left corner, y up --
    matplotlib's own convention, so this is a scale change, not a flip.
    """
    x, y, _, _ = parent_rect
    return (x + float(pos_mm[0]) / WIDTH_MM,
            y + float(pos_mm[1]) / HEIGHT_MM)
